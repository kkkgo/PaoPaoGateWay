const CF_PROXY_VALUES: [&str; 3] = ["yes", "no", "both"];

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum IniError {
    #[error("unclosed quote at line {line}: {key}=…")]
    UnclosedQuote { line: usize, key: String },
    #[error("cannot read {path}: {msg}")]
    Read { path: String, msg: String },
}

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Ini {
    map: BTreeMap<String, String>,
}

impl Ini {

    pub fn parse(text: &str) -> Result<Self, IniError> {
        Self::scan(text, true).map(|(ini, _)| ini)
    }

    pub fn parse_lossy(text: &str) -> Self {
        Self::scan(text, false)
            .map(|(ini, _)| ini)
            .unwrap_or_default()
    }

    pub fn read(path: &str) -> Result<Self, IniError> {
        let text = std::fs::read_to_string(path).map_err(|e| IniError::Read {
            path: path.to_string(),
            msg: e.to_string(),
        })?;
        Self::parse(&text)
    }

    pub fn read_lossy(path: &str) -> Self {
        std::fs::read_to_string(path)
            .map(|t| Self::parse_lossy(&t))
            .unwrap_or_default()
    }

    pub fn raw(&self, key: &str) -> Option<&str> {
        self.map.get(key).map(String::as_str)
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.raw(key).filter(|s| !s.is_empty())
    }

    pub fn effective(&self, key: &str) -> &str {
        self.get(key)
            .unwrap_or_else(|| default_of(key).unwrap_or(""))
    }

    pub fn iter(&self) -> impl Iterator<Item = (&str, &str)> {
        self.map.iter().map(|(k, v)| (k.as_str(), v.as_str()))
    }

    fn extra_keys(&self) -> impl Iterator<Item = (&str, &str)> {
        self.iter().filter(|(k, _)| default_of(k).is_none())
    }

    pub fn export(&self) -> String {
        let mut out = String::with_capacity(2048);
        out.push_str("# generated by `ppgw -ini-export`; every key is always assigned\n");
        for key in KEYS {
            let val = self.effective(key.name);
            let val = if key.name == "cf_proxy" {
                clamp_cf_proxy(val)
            } else {
                val
            };
            let _ = writeln!(out, "{}={}", key.name, shell_quote(val));
        }
        for (name, val) in self.extra_keys() {
            let _ = writeln!(out, "{name}={}", shell_quote(val));
        }
        out
    }

    pub fn warnings(&self) -> Vec<String> {
        let mut w = Vec::new();
        if let Some(v) = self.get("cf_proxy")
            && !CF_PROXY_VALUES.contains(&v)
        {
            w.push(format!("unknown cf_proxy=[{v}], treat as yes"));
        }
        w
    }

    fn scan(text: &str, strict: bool) -> Result<(Self, usize), IniError> {
        let mut map = BTreeMap::new();
        let mut skipped = 0usize;

        for (idx, raw) in text.replace('\r', "\n").split('\n').enumerate() {
            let line = raw.trim_start();
            let Some((key, rest)) = split_assignment(line) else {
                continue;
            };
            match scan_value(rest) {
                Ok(v) => {

                    map.insert(key.to_string(), v);
                }
                Err(()) => {
                    if strict {
                        return Err(IniError::UnclosedQuote {
                            line: idx + 1,
                            key: key.to_string(),
                        });
                    }
                    skipped += 1;
                }
            }
        }
        Ok((Self { map }, skipped))
    }
}

pub fn default_of(key: &str) -> Option<&'static str> {
    KEYS.iter().find(|k| k.name == key).map(|k| k.default)
}

fn clamp_cf_proxy(v: &str) -> &str {
    if CF_PROXY_VALUES.contains(&v) {
        v
    } else {
        "yes"
    }
}

fn split_assignment(line: &str) -> Option<(&str, &str)> {
    let eq = line.find('=')?;
    let key = &line[..eq];
    if key.is_empty() || !key.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
        return None;
    }
    Some((key, &line[eq + 1..]))
}

fn scan_value(rest: &str) -> Result<String, ()> {
    let mut out = String::with_capacity(rest.len());
    let mut it = rest.chars();
    while let Some(c) = it.next() {
        match c {

            '\'' => loop {
                match it.next() {
                    Some('\'') => break,
                    Some(ch) => out.push(ch),
                    None => return Err(()),
                }
            },

            '"' => loop {
                match it.next() {
                    Some('"') => break,
                    Some('\\') => match it.next() {
                        Some(n @ ('"' | '\\' | '$' | '`')) => out.push(n),
                        Some(n) => {
                            out.push('\\');
                            out.push(n);
                        }
                        None => return Err(()),
                    },
                    Some(ch) => out.push(ch),
                    None => return Err(()),
                }
            },
            '\\' => match it.next() {
                Some(n) => out.push(n),

                None => return Err(()),
            },

            c if c.is_whitespace() => break,
            c => out.push(c),
        }
    }
    Ok(out)
}

fn shell_quote(v: &str) -> String {
    let mut out = String::with_capacity(v.len() + 2);
    out.push('\'');
    for c in v.chars() {
        if c == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(c);
        }
    }
    out.push('\'');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn p(text: &str) -> Ini {
        Ini::parse(text).expect("parse")
    }

    #[test]
    fn last_assignment_wins() {
        let ini = p("suburl=http://example.com/a.yaml\nsuburl=http://a.com/b.yaml\n");
        assert_eq!(ini.get("suburl"), Some("http://a.com/b.yaml"));
    }

    #[test]
    fn trailing_comment_is_not_part_of_value() {

        let ini = p("suburl=http://a.com/b.yaml #keep this one\n");
        assert_eq!(ini.get("suburl"), Some("http://a.com/b.yaml"));

        let ini = p("clash_web_password=pa#ss\n");
        assert_eq!(ini.get("clash_web_password"), Some("pa#ss"));

        let ini = p("clash_web_password=#hash\n");
        assert_eq!(ini.get("clash_web_password"), Some("#hash"));

        let ini = p("ext_node=\"Traffic|Expire| GB #1\"\n");
        assert_eq!(ini.get("ext_node"), Some("Traffic|Expire| GB #1"));
    }

    #[test]
    fn comment_and_blank_lines_are_skipped() {
        let ini = p("#paopao-gateway\n\n; note\n# admin_cidr=10.0.0.0/8\nmode=free\n");
        assert_eq!(ini.get("mode"), Some("free"));
        assert_eq!(ini.raw("admin_cidr"), None);
    }

    #[test]
    fn crlf_and_cr_only_line_endings() {
        let ini = p("mode=suburl\r\nfake_cidr=7.0.0.0/8\r\n");
        assert_eq!(ini.get("mode"), Some("suburl"));
        assert_eq!(ini.get("fake_cidr"), Some("7.0.0.0/8"));

        let ini = p("mode=suburl\rfake_cidr=7.0.0.0/8\r");
        assert_eq!(ini.get("fake_cidr"), Some("7.0.0.0/8"));
    }

    #[test]
    fn quotes_are_stripped_not_trimmed() {
        assert_eq!(p("a=\"x\"\n").get("a"), Some("x"));
        assert_eq!(p("a='x'\n").get("a"), Some("x"));

        assert_eq!(p("a=\"x'y'z\"\n").get("a"), Some("x'y'z"));
        assert_eq!(p("a=pre\"mid\"post\n").get("a"), Some("premidpost"));

        assert_eq!(p("a='\"x\"'\n").get("a"), Some("\"x\""));
    }

    #[test]
    fn unclosed_quote_is_an_error() {
        assert_eq!(
            Ini::parse("mode=free\nsuburl=\"http://a.com/b\n"),
            Err(IniError::UnclosedQuote {
                line: 2,
                key: "suburl".to_string(),
            })
        );

        assert!(Ini::parse("suburl=http://a.com/b\"\n").is_err());

        assert!(Ini::parse("a=\"x\"y\"\n").is_err());

        let ini = Ini::parse_lossy("mode=free\nsuburl=\"http://a.com/b\n");
        assert_eq!(ini.get("mode"), Some("free"));
        assert_eq!(ini.raw("suburl"), None);
    }

    #[test]
    fn no_expansion_of_shell_constructs() {

        let ini = p("suburl=$(reboot)\ncloudflared_token=`id`\nex_dns=$HOME\n");
        assert_eq!(ini.get("suburl"), Some("$(reboot)"));
        assert_eq!(ini.get("cloudflared_token"), Some("`id`"));
        assert_eq!(ini.get("ex_dns"), Some("$HOME"));
    }

    #[test]
    fn export_assigns_every_known_key() {
        let out = Ini::default().export();
        for key in KEYS {
            assert!(
                out.contains(&format!("\n{}=", key.name)),
                "export must assign {}",
                key.name
            );
        }
    }

    #[test]
    fn export_fills_defaults_and_keeps_values() {
        let out = p("mode=suburl\nadmin_cidr=10.0.0.0/8\n").export();
        assert!(out.contains("mode='suburl'\n"), "{out}");
        assert!(out.contains("admin_cidr='10.0.0.0/8'\n"), "{out}");
        assert!(out.contains("dns_ip='223.5.5.5'\n"), "{out}");
        assert!(out.contains("subtime='1d'\n"), "{out}");
    }

    #[test]
    fn removed_key_exports_as_default_not_stale() {

        let before = p("admin_cidr=10.10.10.0/24\nproxy_cidr=10.10.10.0/24\n").export();
        let after = p("#admin_cidr=10.10.10.0/24\n#proxy_cidr=10.10.10.0/24\n").export();
        assert!(before.contains("admin_cidr='10.10.10.0/24'\n"));
        assert!(after.contains("admin_cidr=''\n"), "{after}");
        assert!(after.contains("proxy_cidr=''\n"), "{after}");
        assert_ne!(before, after, "hash of the export must change");
    }

    #[test]
    fn explicit_empty_value_falls_back_to_default() {
        let ini = p("dns_ip=\n");
        assert_eq!(ini.raw("dns_ip"), Some(""));
        assert_eq!(ini.effective("dns_ip"), "223.5.5.5");
    }

    #[test]
    fn export_quotes_are_injection_proof() {
        let out = p("clash_web_password='a'\\''b$(id) c'\n").export();
        assert!(out.contains(r"clash_web_password='a'\''b$(id) c'"), "{out}");
    }

    #[test]
    fn unknown_keys_survive_export() {
        let out = p("mode=free\nfuture_key=42\n").export();
        assert!(out.contains("future_key='42'\n"), "{out}");
    }

    #[test]
    fn cf_proxy_is_clamped_with_warning() {
        let ini = p("cf_proxy=maybe\n");
        assert!(ini.export().contains("cf_proxy='yes'\n"));
        assert_eq!(ini.warnings().len(), 1);
        assert!(p("cf_proxy=both\n").export().contains("cf_proxy='both'\n"));
        assert!(p("cf_proxy=both\n").warnings().is_empty());
    }

    #[test]
    fn export_is_stable_across_key_order_and_formatting() {
        let a = p("mode=free\nudp_enable=yes\n").export();
        let b = p("udp_enable=\"yes\"\r\nmode='free'\r\n").export();
        assert_eq!(a, b, "hash must not move on cosmetic edits");
    }
}
